/**
 * WHAT THE STUDIO SAYS WHEN BYTES ARE NOT A READABLE IMAGE (#209 item 1).
 *
 * # Why this module exists
 *
 * One customer sentence was written out INLINE FIVE TIMES, exported nowhere:
 * `inkUploadDoor.ts`, `inkUploadService.ts`, `referenceAttachService.ts`, and
 * TWICE in `server/routes/castingV2.ts`. Any one of them could have been
 * reworded and nothing would have gone red — working law 4 wearing a refusal's
 * clothes, which is the same defect `briefRefusalCopy.ts` was built to cure for
 * the roll entrance and this follows its shape deliberately.
 *
 * #209 filed the two route sites as a pair. **The sweep found five** (law 7:
 * the class, not the instance), and the three it did not name are the more
 * interesting ones, because they already carry `code: "unreadable"` — so the
 * sentence was half-named and half-anonymous depending on which door you
 * arrived at.
 *
 * # ⚠ Why there is NO new door id here, stated so the next sweep does not
 * re-derive it
 *
 * The obvious next step is to declare these to the capability atlas. It was
 * measured and deliberately NOT taken, for two reasons read at the artifacts
 * on 2026-08-29:
 *
 * 1. **`unreadable` is ALREADY a declared door and it is a different one.**
 *    `capability-atlas.json` holds `unreadable` as an `interpreter-refusal`
 *    with seventeen sites in `castingIntent.ts` / `openLaneKind.ts` /
 *    `refineInterpreter.ts`. Declaring these bare would auto-attach the
 *    interpreter's line to an upload door — precisely the conflation #206
 *    qualified `roll.*` to avoid. Doing it properly means a per-entrance
 *    qualified table (`ink.*`, `reference.*`), not a bare key.
 * 2. **A declared id carries a same-commit obligation.** `capabilityAtlas.mts`
 *    raises a hard ERROR for a door with no corpus row, no `UNREACHABLE_DOORS`
 *    reason and no `KNOWN_DEBTS` line. For these doors all three are wrong: the
 *    corpus drives the refine entrance and would need a new driver, they are
 *    plainly reachable, and a debt line is a founder-visible act.
 *
 * So this module is the law-4 half ONLY, and it is honest about being half:
 * the sentence now has one author, and the id remains #209's open remainder
 * with the sizing recorded on that card.
 *
 * ⚠ **AND THE CONFLATION REASON 1 DESCRIBES HAS ALREADY ARRIVED BY A SIDE
 * DOOR — through the PIN reader, not the door declaration** (gate review of
 * PR #213, verified at the artifact). `uploadRefusalCopy.test.ts` drives both
 * byte doors and therefore writes `code: "unreadable"` as a quoted literal, and
 * the atlas counts a test that names an id as a test that PINS it. So the
 * interpreter's `unreadable` door went from 20 pinning tests to 21, and the
 * 21st proves nothing whatever about the interpreter — it is an upload door's
 * arm wearing the same word.
 *
 * Nothing is done about it here on purpose: the pin reader is working as
 * designed at its current granularity, and narrowing it is the per-entrance
 * qualification this module declined to build tonight. It is written down so
 * the count is not later read as 21 tests of the interpreter's sentence — and
 * because it is the cheapest possible demonstration that reason 1 is a real
 * hazard rather than a cautious one.
 *
 * # The one structural rule
 *
 * **This file imports nothing.** Not because the atlas reads it — it does not —
 * but because the module it copies its shape from cannot afford to, and a copy
 * that quietly drops the property is how the shape stops meaning anything.
 * `uploadRefusalCopy.test.ts` pins the import list, the sentence's bytes, and
 * that no SIXTH inline copy has appeared in the tree.
 */

