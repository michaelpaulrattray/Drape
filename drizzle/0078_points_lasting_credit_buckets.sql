-- ============================================================================
-- THE RULE THEY CARRY
-- ============================================================================
--
--   Top-ups            never expire (`purchasedBalance`, unchanged)
--   Starting credits   never expire                      -> keptBalance
--   Referral credits   never expire                      -> keptBalance
