--
-- Each `…Balance` is an upper bound read the way `purchasedBalance` is: the
-- balance spends plan -> promo -> kept -> purchased, so a bucket's remaining
-- credits are the lesser of its bound and what the later buckets leave over.
-- Nothing is written on the spend path.
